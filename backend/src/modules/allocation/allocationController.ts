import { Request, Response, NextFunction } from 'express';
import { optimizeReliefAllocation } from './allocationEngine.js';
import { dbStore } from '../../db/index.js';
import { AppError } from '../../middleware/errorHandler.js';
import { ReliefOrder } from '../../types/index.js';
import { v4 as uuidv4 } from 'uuid';
import { calculateHaversineDistanceKm, estimateTravelMinutes } from '../../utils/haversine.js';

export async function generateReliefPlan(
  req: Request,
  res: Response,
  next: NextFunction
): Promise<void> {
  try {
    const { incidentId, warehouseIds, prioritizeUrgency } = req.body;

    if (!incidentId) {
      // default to first active incident if not provided
      const firstInc = dbStore.getIncidents()[0];
      if (!firstInc) {
        throw new AppError('No active incidents found in database', 404);
      }
      const plan = optimizeReliefAllocation({
        incidentId: firstInc.id,
        warehouseIds,
        prioritizeUrgency,
      });
      res.json(plan);
      return;
    }

    const plan = optimizeReliefAllocation({
      incidentId,
      warehouseIds,
      prioritizeUrgency,
    });

    res.json(plan);
  } catch (err) {
    next(err);
  }
}

export async function convertPlanToDraftOrders(
  req: Request,
  res: Response,
  next: NextFunction
): Promise<void> {
  try {
    const { planId, incidentId } = req.body;

    const targetIncidentId = incidentId || dbStore.getIncidents()[0]?.id;
    const plan = optimizeReliefAllocation({ incidentId: targetIncidentId });

    const createdDraftOrders: ReliefOrder[] = [];

    for (const alloc of plan.allocations) {
      if (alloc.allocatedFood === 0 && alloc.allocatedWater === 0 && alloc.allocatedMedical === 0) {
        continue;
      }

      const loc = dbStore.getLocationById(alloc.locationId);
      const wh = dbStore.getWarehouseById(alloc.warehouseId);
      if (!loc || !wh) continue;

      const dist = calculateHaversineDistanceKm(wh.latitude, wh.longitude, loc.latitude, loc.longitude);
      const travelMins = estimateTravelMinutes(dist, loc.accessRoadStatus);

      const orderNumber = `ORD-2026-${Math.floor(100 + Math.random() * 900)}`;

      const draftOrder: ReliefOrder = {
        id: uuidv4(),
        orderNumber,
        incidentId: targetIncidentId,
        warehouseId: wh.id,
        warehouseName: wh.name,
        destinationLocationId: loc.id,
        destinationLocationName: loc.name,
        status: 'DRAFT',
        assignedVehicleType: loc.accessRoadStatus === 'COMPLETELY_FLOODED' ? 'RESCUE_BOAT' : 'TRUCK_4x4',
        estimatedDistanceKm: dist,
        estimatedTravelMinutes: travelMins,
        roadHazardWarning:
          loc.accessRoadStatus !== 'OPEN'
            ? `Road status reported as ${loc.accessRoadStatus}. Exercise tactical caution.`
            : undefined,
        routeConfidence: 'VERIFIED_SAFE',
        createdAt: new Date().toISOString(),
        items: [
          {
            itemCategory: 'FOOD',
            itemName: 'High-Energy Fortified Ration Packs (MRE)',
            unit: 'packets',
            quantityRequested: loc.requiredFoodPackets,
            quantityAllocated: alloc.allocatedFood,
          },
          {
            itemCategory: 'WATER',
            itemName: 'Potable Water Jerrycans (10L)',
            unit: 'liters',
            quantityRequested: loc.requiredDrinkingWaterLiters,
            quantityAllocated: alloc.allocatedWater,
          },
          {
            itemCategory: 'MEDICAL',
            itemName: 'Emergency Waterborne Disease Trauma Kit',
            unit: 'kits',
            quantityRequested: loc.requiredMedicalKits,
            quantityAllocated: alloc.allocatedMedical,
          },
        ],
        notes: `Draft generated by Deterministic Optimization Engine from plan ${planId || plan.planId}.`,
      };

      dbStore.saveOrder(draftOrder);
      createdDraftOrders.push(draftOrder);
    }

    res.status(201).json({
      message: `Successfully created ${createdDraftOrders.length} DRAFT relief orders awaiting disaster manager approval.`,
      orders: createdDraftOrders,
    });
  } catch (err) {
    next(err);
  }
}
